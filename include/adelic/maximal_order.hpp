// fp_mulmod (multiply two F_p[x] polynomials and reduce modulo a
// third) now lives in fp_poly.hpp -- the single canonical definition,
// available here via dedekind_factorization.hpp's include of it.

// The squarefree radical of f_p mod p: the product of the DISTINCT
// irreducible factors (each taken once, regardless of multiplicity
// in f_p itself).
inline FpPoly squarefree_radical_fp(const std::vector<FpFactor>& factors, long long p) {
    FpPoly rad;
    rad.p = p;
    rad.c = {1};  // start at the constant polynomial 1
    for (const auto& fac : factors) {
        rad = fp_mul(rad, fac.g);
    }
    while (rad.c.size() > 1 && rad.c.back() == 0) rad.c.pop_back();
    return rad;
}

// Coefficient vector of an FpPoly, zero-padded/truncated to length n.
inline std::vector<long long> fp_poly_to_vector(const FpPoly& g, std::size_t n) {
    std::vector<long long> v(n, 0);
    for (std::size_t i = 0; i < g.c.size() && i < n; ++i) v[i] = g.c[i];
    return v;
}

// Basis (via Gaussian elimination mod p) of the F_p-linear SPAN of a
// set of row vectors.  Used for the radical ideal J and for the
// multiplier-ring intersection J ∩ ann(J).
inline std::vector<std::vector<long long>> fp_row_span(
    std::vector<std::vector<long long>> rows, long long p) {
    const std::size_t n = rows.size();
    const std::size_t m = n == 0 ? 0 : rows[0].size();
    std::size_t r = 0;
    for (std::size_t col = 0; col < m && r < n; ++col) {
        std::size_t sel = r;
        while (sel < n && rows[sel][col] % p == 0) ++sel;
        if (sel == n) continue;
        std::swap(rows[r], rows[sel]);
        long long piv = ((rows[r][col] % p) + p) % p;
        long long inv = 0;
        for (long long k = 1; k < p; ++k) {
            if ((piv * k) % p == 1) { inv = k; break; }
        }
        for (std::size_t j = 0; j < m; ++j) rows[r][j] = ((rows[r][j] * inv) % p + p) % p;
        for (std::size_t i = 0; i < n; ++i) {
            if (i == r) continue;
            long long factor = ((rows[i][col] % p) + p) % p;
            if (factor == 0) continue;
            for (std::size_t j = 0; j < m; ++j) {
                rows[i][j] = ((rows[i][j] - factor * rows[r][j]) % p + p * p) % p;
            }
        }
        ++r;
    }
    rows.resize(r);
    return rows;
}

// Kernel (as a list of basis vectors, coefficients in [0, p)) of an
// n x n matrix over F_p, via Gaussian elimination mod p.  `p` must be
// prime (so every nonzero element of F_p is invertible -- used here
// to find pivots).
inline std::vector<std::vector<long long>> fp_matrix_kernel(
    std::vector<std::vector<long long>> M, long long p) {
    const std::size_t n = M.size();
    const std::size_t m = n == 0 ? 0 : M[0].size();
    std::vector<int> pivot_col(n, -1);
    std::size_t row = 0;
    std::vector<int> pivot_of_col(m, -1);
    for (std::size_t col = 0; col < m && row < n; ++col) {
        std::size_t sel = row;
        while (sel < n && M[sel][col] % p == 0) ++sel;
        if (sel == n) continue;  // no pivot in this column
        std::swap(M[row], M[sel]);
        long long piv = ((M[row][col] % p) + p) % p;
        long long inv = 0;
        for (long long k = 1; k < p; ++k) {
            if ((piv * k) % p == 1) { inv = k; break; }
        }
        for (std::size_t j = 0; j < m; ++j) {
            M[row][j] = ((M[row][j] * inv) % p + p) % p;
        }
        for (std::size_t r = 0; r < n; ++r) {
            if (r == row) continue;
            long long factor = ((M[r][col] % p) + p) % p;
            if (factor == 0) continue;
            for (std::size_t j = 0; j < m; ++j) {
                M[r][j] = ((M[r][j] - factor * M[row][j]) % p + p * p) % p;
            }
        }
        pivot_of_col[col] = static_cast<int>(row);
        ++row;
    }
    // Free columns (no pivot) parametrize the kernel.
    std::vector<std::vector<long long>> kernel;
    for (std::size_t col = 0; col < m; ++col) {
        if (pivot_of_col[col] != -1) continue;
        std::vector<long long> vec(m, 0);
        vec[col] = 1;
        for (std::size_t c2 = 0; c2 < m; ++c2) {
            if (pivot_of_col[c2] == -1) continue;
            // Row pivot_of_col[c2] has a 1 in column c2 (after
            // reduction above) and some value in column `col`;
            // solve for that pivot variable.
            long long coeff = M[static_cast<std::size_t>(pivot_of_col[c2])][col];
            vec[c2] = ((-coeff) % p + p) % p;
        }
        kernel.push_back(vec);
    }
    return kernel;
}

// Intersection of two row subspaces of F_p^n.  A vector in the
// intersection has the form u*A = v*B; equivalently it is obtained
// from a kernel vector of the block matrix [A^T | -B^T].
inline std::vector<std::vector<long long>> fp_row_space_intersection(
        const std::vector<std::vector<long long>>& A,
        const std::vector<std::vector<long long>>& B, long long p) {
    const std::size_t n = A.empty() ? (B.empty() ? 0 : B[0].size()) : A[0].size();
    std::vector<std::vector<long long>> block(
        n, std::vector<long long>(A.size() + B.size(), 0));
    for (std::size_t col = 0; col < A.size(); ++col)
        for (std::size_t row = 0; row < n; ++row)
            block[row][col] = ((A[col][row] % p) + p) % p;
    for (std::size_t col = 0; col < B.size(); ++col)
        for (std::size_t row = 0; row < n; ++row)
            block[row][A.size() + col] = ((-B[col][row]) % p + p) % p;
    auto relations = fp_matrix_kernel(block, p);
    std::vector<std::vector<long long>> intersection;
    for (const auto& rel : relations) {
        std::vector<long long> v(n, 0);
        for (std::size_t i = 0; i < A.size(); ++i)
            for (std::size_t j = 0; j < n; ++j)
                v[j] = (v[j] + rel[i] * A[i][j]) % p;
        intersection.push_back(std::move(v));
    }
    return fp_row_span(intersection, p);
}

// Integer Hermite Normal Form (row style, upper triangular) of a
// (rows) x n integer matrix, via elementary row operations
// (long long -- fine for the small entries this module deals with;
// NOT safe for large inputs where intermediate values could
// overflow 64 bits).  Returns the n x n HNF basis (assumes the input
// spans a full-rank n-dimensional lattice, which is guaranteed here
// since the p*e_i rows alone already have full rank n).
//
// Column reduction uses pairwise extended-Euclid combination (NOT
// repeated fixed-pivot subtraction): each combining step strictly
// reduces the COUNT of nonzero rows in the current column by at
// least one, which is what actually guarantees termination -- a
// naive "subtract a multiple of a fixed pivot row" scheme can stall
// forever if a later row's entry is already smaller in magnitude
// than the fixed pivot's (confirmed by an infinite loop during this
// module's first version).
inline std::vector<std::vector<long long>> integer_hnf(
    std::vector<std::vector<long long>> rows, std::size_t n) {
    std::size_t r = 0;
    for (std::size_t col = 0; col < n && r < rows.size(); ++col) {
        for (;;) {
            std::size_t i1 = rows.size();
            for (std::size_t i = r; i < rows.size(); ++i) {
                if (rows[i][col] != 0) { i1 = i; break; }
            }
            if (i1 == rows.size()) break;  // column all-zero below row r
            std::size_t i2 = rows.size();
            for (std::size_t i = i1 + 1; i < rows.size(); ++i) {
                if (rows[i][col] != 0) { i2 = i; break; }
            }
            if (i2 == rows.size()) {
                std::swap(rows[r], rows[i1]);
                break;  // exactly one nonzero row left in this column
            }
            // Extended Euclid on (a, b) = (rows[i1][col], rows[i2][col]):
            // find g = gcd(a,b) = s*a + t*b.
            long long a = rows[i1][col], b = rows[i2][col];
            long long old_r = a, cur_r = b;
            long long old_s = 1, cur_s = 0;
            long long old_t = 0, cur_t = 1;
            while (cur_r != 0) {
                long long q = old_r / cur_r;
                long long tmp_r = old_r - q * cur_r; old_r = cur_r; cur_r = tmp_r;
                long long tmp_s = old_s - q * cur_s; old_s = cur_s; cur_s = tmp_s;
                long long tmp_t = old_t - q * cur_t; old_t = cur_t; cur_t = tmp_t;
            }
            long long g = old_r, s = old_s, t = old_t;
            long long bg = (g != 0) ? b / g : 0;
            long long ag = (g != 0) ? a / g : 0;
            std::vector<long long> new1(n), new2(n);
            for (std::size_t j = 0; j < n; ++j) {
                // new1 has column value s*a + t*b = g.
                new1[j] = s * rows[i1][j] + t * rows[i2][j];
                // new2 has column value (b/g)*a - (a/g)*b = 0.
                new2[j] = bg * rows[i1][j] - ag * rows[i2][j];
            }
            rows[i1] = std::move(new1);
            rows[i2] = std::move(new2);
        }
        if (rows[r][col] < 0) {
            for (std::size_t j = 0; j < n; ++j) rows[r][j] = -rows[r][j];
        }
        if (rows[r][col] != 0) ++r;
    }
    rows.resize(n);
    return rows;
}

// Exact integer determinant via fraction-free (Bareiss) Gaussian
// elimination.  Safe for the small matrices (n <= 5) and small
// entries this module produces; not a general-purpose big-integer
// determinant routine.
inline long long integer_determinant(std::vector<std::vector<long long>> M) {
    const std::size_t n = M.size();
    long long prev_pivot = 1;
    int sign = 1;
    for (std::size_t k = 0; k + 1 < n; ++k) {
        if (M[k][k] == 0) {
            std::size_t sw = k + 1;
            while (sw < n && M[sw][k] == 0) ++sw;
            if (sw == n) return 0;
            std::swap(M[k], M[sw]);
            sign = -sign;
        }
        for (std::size_t i = k + 1; i < n; ++i) {
            for (std::size_t j = k + 1; j < n; ++j) {
                M[i][j] = (M[i][j] * M[k][k] - M[i][k] * M[k][j]) / prev_pivot;
            }
            M[i][k] = 0;
        }
        prev_pivot = M[k][k];
    }
    return sign * (n == 0 ? 1 : M[n - 1][n - 1]);
}

// Discriminant of a monic integer polynomial f of degree n, via the
// Sylvester matrix of (f, f') -- disc(f) = (-1)^{n(n-1)/2} * Res(f,f')
// for monic f.  `long long` throughout; fine for the small
// coefficients this project's characteristic polynomials have.
//
// CONFIRMED OVERFLOW, not just a theoretical risk (2026-07-31,
// math/tests/poly_discriminant_bigint_test.cpp -- now
// tests/poly_discriminant_bigint_test.cpp): for x^n-2, this function
// silently returns a WRONG value starting at n=9 -- not merely unable
// to hold a too-large final answer (disc(x^10-2) is only ~5*10^12,
// nowhere near int64's ~9*10^18 ceiling), but genuinely wrong, because
// Bareiss elimination's INTERMEDIATE entries can overflow even when
// the final determinant fits. Confirmed by disagreement with an
// independent from-scratch closed-form re-derivation of disc(x^n-a)
// (see that test file) AND with math/poly_discriminant.hpp's
// arbitrary-precision poly_discriminant_bigint, which agrees with the
// closed form exactly at every tested n. This project's own current
// Pisot-substitution use (degree <=4, small coefficients) is very
// likely safe -- the Sylvester matrix stays small (at most 7x7) and
// entries stay modest -- but this is now a demonstrated, not
// hypothetical, failure mode for anything of higher degree. Use
// poly_discriminant_bigint for anything beyond this project's own
// small-alphabet substitutions.
inline long long poly_discriminant_ll(const std::vector<long long>& f_high_to_low) {
    // f given highest-degree-first, e.g. x^3 - x^2 - 2x - 8 => {1,-1,-2,-8}.
    long long n = static_cast<long long>(f_high_to_low.size()) - 1;
    std::vector<long long> f = f_high_to_low;
    // f' (derivative), highest-degree-first, degree n-1.
    std::vector<long long> fp;
    for (long long i = 0; i < n; ++i) {
        long long deg = n - i;             // degree of f[i]'s term
        fp.push_back(f[static_cast<std::size_t>(i)] * deg);
    }
    long long m = n - 1;  // degree of f'
    // Sylvester matrix: (n+m) x (n+m) = (2n-1) x (2n-1).
    std::size_t size = static_cast<std::size_t>(n + m);
    std::vector<std::vector<long long>> S(size, std::vector<long long>(size, 0));
    // m rows of shifted f (degree n, so n+1 coeffs), for shift = 0..m-1.
    for (long long shift = 0; shift < m; ++shift) {
        for (std::size_t j = 0; j < f.size(); ++j) {
            S[static_cast<std::size_t>(shift)][static_cast<std::size_t>(shift) + j] = f[j];
        }
    }
    // n rows of shifted f', for shift = 0..n-1.
    for (long long shift = 0; shift < n; ++shift) {
        for (std::size_t j = 0; j < fp.size(); ++j) {
            S[static_cast<std::size_t>(m + shift)][static_cast<std::size_t>(shift) + j] = fp[j];
        }
    }
    long long res = integer_determinant(S);
    long long sign_exp = (n * (n - 1) / 2) % 2;
    return (sign_exp == 0) ? res : -res;
}

