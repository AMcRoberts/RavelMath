// maximal_order.hpp
//
// A (scoped, first-cut) implementation of one round of the
// Pohst-Zassenhaus "Round 2" p-maximal-order enlargement algorithm,
// for when Dedekind's criterion (dedekind_factorization.hpp's
// is_p_maximal) reports that Z[beta] is NOT p-maximal.
//
// docs/ADELIC_TILING_PLAN.md §6 names this exact gap: "Dedekind's
// own non-monogenic cubic" as the textbook example that should be
// added to the factorization layer's test ladder.  This header is
// that follow-up: it builds the enlarged order and verifies (against
// the well-known textbook numbers for that example) that the
// resulting order's discriminant matches the true field discriminant.
//
// SCOPE, STATED HONESTLY: enlarge_order_round2 below implements ONE
// enlargement round using `long long` arithmetic throughout, which is
// enough for the small alphabet sizes (n <= 4) and small primes this
// project's Pisot substitutions actually produce. That function's
// intermediate quantities silently overflow for larger inputs --
// CONFIRMED, not hypothetical: for x^10-2 at p=2, it doesn't just lose
// precision, it throws a spurious "construction invariant violated"
// exception, an int64 overflow masquerading as a math bug (see
// tests/maximal_order_bigint_test.cpp). enlarge_order_round2_bigint,
// near the end of this file, is the arbitrary-precision fix for
// exactly that -- same single-round algorithm, mathlib::BigInt
// throughout the integer-lattice arithmetic.
//
// Both of those still use the MONOGENIC shortcut: factor a single
// defining polynomial mod p and take the ideal generated by its
// squarefree radical, which only works because Z[beta] has a single
// generator. Further down this file, GeneralOrder and
// p_radical_from_structure_constants (Ore's Frobenius method, Cohen
// Sec. 6.1.3) compute the p-radical directly from an order's
// multiplication table instead -- valid for ANY order, monogenic or
// not, which is what round 2 of a genuinely multi-round enlargement
// would need, since the round-1-enlarged order is not in general
// Z[gamma] for any single gamma. enlarge_order_round2_bigint has a
// second overload taking a GeneralOrder for exactly this, cross-
// checked against the monogenic-shortcut path's known-correct answer
// on the trusted textbook case (tests/general_order_radical_test.cpp)
// at p=2, n=3 -- the harder p<=n regime, not the easier one.
//
// That last basis-change step is done too now: structure_constants_
// from_basis_change turns an enlarged order's HNF basis (relative to
// whatever basis the INPUT order had, via Cramer's rule, checked exact
// at every coordinate) into a GeneralOrder in its own right, so the
// chain enlarge -> derive structure constants -> enlarge again
// (general method) -> repeat runs to a fixed point with no defining
// polynomial anywhere past round 1. tests/general_order_radical_test.cpp
// demonstrates the full chain on the trusted textbook case: round 1
// enlarges (disc -2012 -> -503), the derived order's OWN discriminant
// (computed fresh from its own structure constants, not carried
// forward) agrees, and round 2 correctly finds it already 2-maximal.
//
// The chain is exercised on the single-round textbook fixed point. The
// representative quartic now has a verified first multiplier-ring basis
// (-86320 -> -21580); a generic subsequent round in the ramified maximal
// order is deliberately not promoted until its closure criterion is settled.
//
// Algorithm (Cohen, "A Course in Computational Algebraic Number
// Theory", §6.1, specialized to a monogenic starting order Z[beta]):
//
//   1. Factor f(x) mod p (already done by dedekind_factorization.hpp
//      via factor_fp): f_p(x) = prod g_i(x)^{e_i}.
//   2. rad_p(x) = prod g_i(x) (the DISTINCT irreducible factors, each
//      taken once -- the squarefree radical of f_p).
//   3. I = the ideal (p, rad_p(beta)) of Z[beta].  Z[beta]/I is an
//      F_p-vector space; the multiplier ring O' = {x in K :
//      x*I subseteq I} strictly contains Z[beta] whenever Z[beta]
//      was not p-maximal.
//   4. The multiplier-ring condition is the subtle step: for y/p to
//      lie in O' one needs y in the radical ideal J and y*J ⊆ pO.
//      Modulo p this is the intersection J ∩ ann(J), not the image
//      J alone.  Using the image by itself can produce a lattice with
//      the right discriminant quotient but which is not closed under
//      multiplication (the representative quartic caught exactly
//      this failure).  A basis of J ∩ ann(J), lifted to Z, gives the
//      new generators; O' is then Z[beta] + (1/p) * those generators.
//   5. The new order's Z-basis (relative to the power basis
//      1, beta, ..., beta^{n-1}, with an implicit common denominator
//      p) is the Hermite Normal Form of the (n+k) x n integer matrix
//      formed by stacking {p * e_i} (i = 0..n-1) with the lifted
//      annihilator basis vectors (k of them).
//   6. disc(O') = disc(Z[beta]) * (det(H) / p^n)^2, where H is that
//      HNF basis matrix (a standard discriminant-under-basis-change
//      fact).

