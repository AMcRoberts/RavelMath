struct ParentRoleIntegerSchemeReport {
    bool proved{};
    bool arbitrary_integer_displacement{};
    std::size_t root_role{};
    std::size_t zero_kernel_pairs{};
    std::size_t maximum_zero_path_length{};
    std::size_t positive_cycle_length{};
    std::size_t negative_cycle_length{};
};

// A finite catalogue-level theorem scheme.  The hypotheses are all
// replay-checked finite facts: every ordered role pair has a zero-defect path,
// and one common role has +/-1 closed walks.  Repeating those closed walks
// then constructs a path of any integer net defect between any two roles.
// This does not assert the same hypotheses for an unbounded Pisot family; it
// isolates exactly what the family theorem must establish.
inline ParentRoleIntegerSchemeReport derive_parent_role_integer_scheme(
    const CanonicalParentRoleCatalogue& catalogue, std::size_t zero_word_cap,
    std::size_t cycle_word_cap, std::size_t root_role = 0) {
    ParentRoleIntegerSchemeReport out;
    out.root_role = root_role;
    if (!catalogue.proved) return out;
    const auto closure = derive_parent_role_word_closure(catalogue, zero_word_cap, 0);
    const auto cycles = derive_parent_role_unit_cycles(catalogue, cycle_word_cap, root_role);
    if (!closure.zero_net_role_graph_complete || !closure.zero_net_witnesses_verified ||
        !cycles.positive_cycle_found || !cycles.negative_cycle_found) return out;
    out.zero_kernel_pairs = closure.zero_net_pairs;
    out.maximum_zero_path_length = closure.maximum_zero_net_word_length;
    out.positive_cycle_length = cycles.positive_defects.size();
    out.negative_cycle_length = cycles.negative_defects.size();
    out.arbitrary_integer_displacement = true;
    out.proved = true;
    return out;
}

// Builds the finite transport theorem explicitly: zero-kernel witness
// source -> root, a power of the common +/-1 unit cycle, then a zero-kernel
// witness root -> target.  This is the constructive integer extension at a
// bounded displacement radius; no infinite or asymptotic claim is hidden in
// the report.
inline ParentRoleIntegerTransportReport derive_parent_role_integer_transport(
    const CanonicalParentRoleCatalogue& catalogue, std::size_t zero_word_cap,
    std::size_t displacement_radius, std::size_t root_role = 0) {
    ParentRoleIntegerTransportReport out;
    out.root_role = root_role;
    out.displacement_radius = displacement_radius;
    out.zero_word_cap = zero_word_cap;
    if (!catalogue.proved || root_role >= catalogue.role_count || zero_word_cap == 0) return out;
    const auto closure = derive_parent_role_word_closure(catalogue, zero_word_cap, 0);
    const auto cycles = derive_parent_role_unit_cycles(catalogue, zero_word_cap, root_role);
    if (!closure.zero_net_role_graph_complete || !closure.zero_net_witnesses_verified ||
        !cycles.positive_cycle_found || !cycles.negative_cycle_found) return out;
    using Key = std::pair<std::size_t,std::size_t>;
    std::map<Key, ParentRoleWordClosureReport::ZeroNetWitness> zero_paths;
    for (const auto& witness : closure.zero_net_witnesses)
        zero_paths[{witness.source_role, witness.target_role}] = witness;
    std::set<std::tuple<std::size_t,std::size_t,long long>> direct;
    for (const auto& edge : catalogue.edges)
        direct.insert({edge.source_role, edge.target_role, edge.defect});
    auto append_segment = [](std::vector<std::size_t>& roles,
                             std::vector<long long>& defects,
                             const std::vector<std::size_t>& next_roles,
                             const std::vector<long long>& next_defects) {
        if (next_roles.empty() || next_roles.size() != next_defects.size() + 1) return false;
        if (roles.empty()) {
            roles = next_roles;
            defects = next_defects;
            return true;
        }
        if (roles.back() != next_roles.front()) return false;
        defects.insert(defects.end(), next_defects.begin(), next_defects.end());
        roles.insert(roles.end(), next_roles.begin() + 1, next_roles.end());
        return true;
    };
    out.every_word_replayed = true;
    for (std::size_t source = 0; source < catalogue.role_count; ++source)
        for (std::size_t target = 0; target < catalogue.role_count; ++target)
            for (long long displacement = -static_cast<long long>(displacement_radius);
                 displacement <= static_cast<long long>(displacement_radius); ++displacement) {
                std::vector<std::size_t> roles;
                std::vector<long long> defects;
                const auto& left = zero_paths.at({source, root_role});
                const auto& right = zero_paths.at({root_role, target});
                bool ok = append_segment(roles, defects, left.roles, left.defects);
                const auto& cycle = displacement >= 0 ? cycles.positive_roles : cycles.negative_roles;
                const auto& cycle_defects = displacement >= 0 ? cycles.positive_defects : cycles.negative_defects;
                const auto repetitions = static_cast<std::size_t>(
                    displacement >= 0 ? displacement : -displacement);
                for (std::size_t r = 0; r < repetitions && ok; ++r)
                    ok = append_segment(roles, defects, cycle, cycle_defects);
                ok = ok && append_segment(roles, defects, right.roles, right.defects);
                long long sum = 0;
                if (ok) {
                    for (std::size_t k = 0; k < defects.size(); ++k) {
                        sum += defects[k];
                        if (!direct.count({roles[k], roles[k + 1], defects[k]})) { ok = false; break; }
                    }
                    ok = ok && roles.front() == source && roles.back() == target && sum == displacement;
                }
                ++out.transported_words;
                if (!ok) { ++out.failed_words; out.every_word_replayed = false; }
                else out.maximum_transport_word_length =
                    std::max(out.maximum_transport_word_length, defects.size());
            }
    out.proved = out.every_word_replayed;
    return out;
}

// Profiles the finite displacement window without extrapolating past the
// supplied word cap.  Each entry is independently witness-replayed by the
// underlying closure operation; the profile only summarizes those finite
// certificates and records the first scale at which a state is missing.
inline ParentRoleWindowProfile derive_parent_role_window_profile(
    const CanonicalParentRoleCatalogue& catalogue,
    std::size_t max_word_length, std::size_t max_radius) {
    ParentRoleWindowProfile out;
    out.max_word_length = max_word_length;
    out.max_radius_tested = max_radius;
    if (!catalogue.proved || max_word_length == 0) return out;
    out.missing_by_radius.reserve(max_radius + 1);
    for (std::size_t radius = 0; radius <= max_radius; ++radius) {
        const auto closure = derive_parent_role_word_closure(
            catalogue, max_word_length, radius);
        out.missing_by_radius.push_back(closure.integer_window_missing_pairs);
        if (closure.integer_window_complete)
            out.largest_complete_radius = radius;
    }
    out.proved = true;
    return out;
}

// Checks whether the one-step relation is already closed under composition.
// Usually it is not: generator words are expected to create longer paths.
// Recording the first missing composite makes that distinction explicit and
// prevents mistaking a finite generating relation for a finite group law.
inline ParentRoleCompositionReport derive_parent_role_composition(
    const CanonicalParentRoleCatalogue& catalogue) {
    ParentRoleCompositionReport out;
    if (!catalogue.proved) return out;
    std::set<std::tuple<std::size_t,std::size_t,long long>> direct;
    for (const auto& edge : catalogue.edges)
        direct.insert({edge.source_role, edge.target_role, edge.defect});
    for (const auto& first : catalogue.edges) for (const auto& second : catalogue.edges) {
        if (first.target_role != second.source_role) continue;
        ++out.composable_pairs;
        const auto net = first.defect + second.defect;
        if (direct.count({first.source_role, second.target_role, net})) {
            ++out.closed_pairs;
        } else {
            ++out.missing_pairs;
            if (out.missing_pairs == 1)
                out.first_missing = {first.source_role, first.target_role, second.target_role,
                                     first.defect, second.defect};
        }
    }
    out.one_step_closed = (out.missing_pairs == 0);
    out.proved = true;
    return out;
}

// Tests the first possible group-extension obstruction: whether a defect
// label acts as a function on pair roles.  Parent occurrences are retained,
// so this distinguishes genuine multiplicity from merely having two target
// roles.  A failure is useful data, not an implementation error: it says the
// right theorem must use a relation/sofic correspondence rather than a plain
// action.
inline ParentRoleRegularityReport derive_parent_role_regularity(
    const CanonicalParentRoleCatalogue& catalogue) {
    ParentRoleRegularityReport out;
    if (!catalogue.proved) return out;
    std::map<std::pair<std::size_t,long long>, std::set<std::size_t>> targets;
    std::map<std::tuple<std::size_t,std::size_t,long long>, std::size_t> occurrences;
    for (const auto& edge : catalogue.edges) {
        targets[{edge.source_role, edge.defect}].insert(edge.target_role);
        ++occurrences[{edge.source_role, edge.target_role, edge.defect}];
    }
    out.label_single_valued = true;
    out.occurrence_single_valued = true;
    for (const auto& [key, destinations] : targets) {
        out.max_targets_for_source_label =
            std::max(out.max_targets_for_source_label, destinations.size());
        if (destinations.size() > 1) {
            out.label_single_valued = false;
            ++out.branching_source_labels;
        }
    }
    for (const auto& [_, count] : occurrences) {
        out.max_occurrences_for_source_target_label =
            std::max(out.max_occurrences_for_source_target_label, count);
        if (count > 1) out.occurrence_single_valued = false;
    }
    out.proved = true;
    return out;
}

inline ParentRoleHolonomyReport derive_parent_role_holonomy(
    const CanonicalParentRoleCatalogue& catalogue) {
    ParentRoleHolonomyReport out;
    if (!catalogue.proved) return out;
    const std::size_t N = catalogue.role_count;
    std::vector<std::vector<std::pair<std::size_t,long long>>> adj(N), radj(N);
    for (const auto& edge : catalogue.edges) {
        adj[edge.source_role].push_back({edge.target_role, edge.defect});
        radj[edge.target_role].push_back({edge.source_role, edge.defect});
    }
    out.edge_count = catalogue.edges.size();
    std::vector<char> seen(N, false);
    std::vector<std::size_t> order;
    std::function<void(std::size_t)> dfs1 = [&](std::size_t v) {
        seen[v] = true;
        for (const auto& [w, _] : adj[v]) if (!seen[w]) dfs1(w);
        order.push_back(v);
    };
    for (std::size_t v = 0; v < N; ++v) if (!seen[v]) dfs1(v);
    std::fill(seen.begin(), seen.end(), false);
    std::function<void(std::size_t,std::vector<std::size_t>&)> dfs2 =
        [&](std::size_t v, std::vector<std::size_t>& component) {
            seen[v] = true; component.push_back(v);
            for (const auto& [w, _] : radj[v]) if (!seen[w]) dfs2(w, component);
        };
    while (!order.empty()) {
        const auto root = order.back(); order.pop_back();
        if (seen[root]) continue;
        ParentRoleHolonomyComponent component;
        dfs2(root, component.roles);
        std::set<std::size_t> members(component.roles.begin(), component.roles.end());
        std::vector<char> assigned(N, false);
        std::vector<long long> potential(N, 0);
        long long g = 0;
        for (const auto root_role : component.roles) if (!assigned[root_role]) {
            assigned[root_role] = true;
            std::vector<std::size_t> stack{root_role};
            while (!stack.empty()) {
                const auto v = stack.back(); stack.pop_back();
                for (const auto& [w, label] : adj[v]) {
                    if (!members.count(w)) continue;
                    const long long expected = potential[v] + label;
                    if (!assigned[w]) {
                        assigned[w] = true; potential[w] = expected; stack.push_back(w);
                    } else {
                        g = std::gcd(g, expected - potential[w]);
                    }
                }
            }
        }
        component.holonomy_gcd = g < 0 ? -g : g;
        component.labels_are_potential = (component.holonomy_gcd == 0);
        if (!component.labels_are_potential) ++out.nontrivial_holonomy_components;
        out.components.push_back(std::move(component));
    }
    out.proved = true;
    return out;
}

inline CanonicalParentRoleCatalogue derive_canonical_parent_role_catalogue(
    const mathlib::QBetaRing& R, const mathlib::RootInterval& beta_I) {
    using namespace mathlib;
    CanonicalParentRoleCatalogue out;
    auto ge = exact_greedy_beta_expansion_of_one(R, beta_I, 128);
    if (!ge.terminated && ge.period_len == 0) {
        out.obstruction = "greedy expansion did not terminate or cycle";
        return out;
    }
    out.digits = ge.digits;
    if (ge.terminated || ge.purely_periodic) {
        out.substitution = canonical_beta_substitution_from_digits(out.digits);
    } else {
        std::vector<long long> pre(out.digits.begin(), out.digits.begin() + ge.preperiod_len);
        std::vector<long long> period(out.digits.begin() + ge.preperiod_len, out.digits.end());
        out.substitution = canonical_beta_substitution_eventually_periodic(pre, period);
    }
    out.alphabet_size = out.substitution.size();
    out.role_count = out.alphabet_size * out.alphabet_size;
    out.parents.resize(out.alphabet_size);
    for (std::size_t parent = 0; parent < out.substitution.size(); ++parent) {
        const auto& image = out.substitution[parent];
        for (std::size_t k = 0; k < image.size(); ++k) {
            const auto inner = static_cast<std::size_t>(image[k]);
            if (inner >= out.alphabet_size) {
                out.obstruction = "substitution image contains an out-of-range letter";
                return out;
            }
            std::vector<long long> prefix(image.begin(), image.begin() + static_cast<std::ptrdiff_t>(k));
            out.parents[inner].push_back({static_cast<long long>(parent), prefix});
            out.prefixes.insert(prefix);
            if (static_cast<long long>(prefix.size()) > out.max_prefix_length)
                out.max_prefix_length = static_cast<long long>(prefix.size());
        }
    }
    for (long long left = 0; left < static_cast<long long>(out.alphabet_size); ++left)
        for (long long right = 0; right < static_cast<long long>(out.alphabet_size); ++right)
            for (const auto& lp : out.parents[static_cast<std::size_t>(left)])
                for (const auto& rp : out.parents[static_cast<std::size_t>(right)]) {
                    const long long defect = static_cast<long long>(rp.prefix.size()) -
                                             static_cast<long long>(lp.prefix.size());
                    out.edges.push_back({out.role(left, right), out.role(lp.parent_letter, rp.parent_letter),
                                         defect, left, right, lp.parent_letter, rp.parent_letter,
                                         lp.prefix, rp.prefix});
                    out.defects.insert(defect);
                    ++out.edge_count_by_defect[defect];
                }
    out.proved = true;
    return out;
}

