// Enumerates the finite prefix of the positive word closure.  The state is
// (starting role, current role, accumulated defect); unlike a tree dump this
// quotient deduplicates equal labelled states and therefore exposes the
// actual finite-state cocycle.  The cap is explicit: an incomplete result is
// still useful evidence and is never reported as an infinite theorem.
inline ParentRoleWordClosureReport derive_parent_role_word_closure(
    const CanonicalParentRoleCatalogue& catalogue, std::size_t max_word_length,
    std::size_t integer_window_radius = 0) {
    ParentRoleWordClosureReport out;
    out.max_word_length = max_word_length;
    out.integer_window_radius = integer_window_radius;
    if (!catalogue.proved || max_word_length == 0) return out;
    std::vector<std::vector<std::pair<std::size_t,long long>>> adj(catalogue.role_count);
    for (const auto& edge : catalogue.edges)
        adj[edge.source_role].push_back({edge.target_role, edge.defect});
    const long long net_bound = catalogue.max_prefix_length *
                                static_cast<long long>(max_word_length);
    std::size_t zero_pairs = 0;
    std::size_t maximum_zero_length = 0;
    const auto window_total = catalogue.role_count * catalogue.role_count *
                              (2 * integer_window_radius + 1);
    for (std::size_t source = 0; source < catalogue.role_count; ++source) {
        std::set<std::pair<std::size_t,long long>> seen;
        std::map<std::pair<std::size_t,long long>, std::size_t> depth_of;
        struct Predecessor { std::pair<std::size_t,long long> state; long long defect; };
        std::map<std::pair<std::size_t,long long>, Predecessor> predecessor;
        std::vector<std::pair<std::size_t,long long>> frontier;
        seen.insert({source, 0});
        depth_of[{source, 0}] = 0;
        frontier.push_back({source, 0});
        for (std::size_t depth = 0; depth < max_word_length; ++depth) {
            std::vector<std::pair<std::size_t,long long>> next;
            for (const auto& [role, net] : frontier)
                for (const auto& [target, label] : adj[role]) {
                    const long long new_net = net + label;
                    if (new_net < -net_bound || new_net > net_bound) continue;
                    const auto state = std::make_pair(target, new_net);
                    if (seen.insert(state).second) {
                        depth_of[state] = depth + 1;
                        predecessor[state] = {{role, net}, label};
                        next.push_back(state);
                    }
                }
            frontier.swap(next);
            if (frontier.empty()) break;
        }
        std::set<std::size_t> zero_targets;
        for (const auto& [target, net] : seen) {
            ++out.reachable_source_target_net_states;
            if (net == 0) {
                zero_targets.insert(target);
                maximum_zero_length = std::max(maximum_zero_length, depth_of[{target, net}]);
                ParentRoleWordClosureReport::ZeroNetWitness witness;
                witness.source_role = source;
                witness.target_role = target;
                auto cursor = std::make_pair(target, net);
                witness.roles.push_back(target);
                while (cursor != std::make_pair(source, 0LL)) {
                    const auto& prev = predecessor.at(cursor);
                    witness.defects.push_back(prev.defect);
                    witness.roles.push_back(prev.state.first);
                    cursor = prev.state;
                }
                std::reverse(witness.roles.begin(), witness.roles.end());
                std::reverse(witness.defects.begin(), witness.defects.end());
                out.zero_net_witnesses.push_back(std::move(witness));
            }
        }
        zero_pairs += zero_targets.size();
        for (long long net = -static_cast<long long>(integer_window_radius);
             net <= static_cast<long long>(integer_window_radius); ++net)
            for (std::size_t target = 0; target < catalogue.role_count; ++target)
                if (seen.count({target, net})) ++out.integer_window_pairs;
    }
    out.zero_net_pairs = zero_pairs;
    out.maximum_zero_net_word_length = maximum_zero_length;
    const auto total_pairs = catalogue.role_count * catalogue.role_count;
    out.zero_net_missing_pairs = total_pairs > zero_pairs ? total_pairs - zero_pairs : 0;
    out.integer_window_missing_pairs = window_total > out.integer_window_pairs
        ? window_total - out.integer_window_pairs : 0;
    out.integer_window_complete = (out.integer_window_missing_pairs == 0);
    out.zero_net_role_graph_complete = (out.zero_net_missing_pairs == 0);
    out.zero_net_witnesses_verified = (out.zero_net_witnesses.size() == out.zero_net_pairs);
    for (const auto& witness : out.zero_net_witnesses) {
        long long sum = 0;
        if (witness.roles.size() != witness.defects.size() + 1 ||
            witness.roles.front() != witness.source_role ||
            witness.roles.back() != witness.target_role) {
            out.zero_net_witnesses_verified = false;
            continue;
        }
        for (std::size_t k = 0; k < witness.defects.size(); ++k) {
            sum += witness.defects[k];
            bool edge_exists = false;
            for (const auto& edge : catalogue.edges)
                if (edge.source_role == witness.roles[k] &&
                    edge.target_role == witness.roles[k + 1] &&
                    edge.defect == witness.defects[k]) { edge_exists = true; break; }
            if (!edge_exists) out.zero_net_witnesses_verified = false;
        }
        if (sum != 0) out.zero_net_witnesses_verified = false;
    }
    out.proved = true;
    return out;
}

